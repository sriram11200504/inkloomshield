'use client';

import React, { useState } from 'react';
import { MacroInsight } from '@/lib/types';
import { Lightbulb, Copy, Check, Send, X, ShieldAlert, ArrowRight } from 'lucide-react';

interface GuidelineAmbiguityModalProps {
  insight: MacroInsight;
  isOpen: boolean;
  onClose: () => void;
}

export function GuidelineAmbiguityModal({ insight, isOpen, onClose }: GuidelineAmbiguityModalProps) {
  const [copied, setCopied] = useState(false);
  const [submitted, setSubmitted] = useState(false);

  if (!isOpen) return null;

  const handleCopy = () => {
    const proposal = `BRAND GOVERNANCE RFC — RULE AMENDMENT PROPOSAL
Subject: Clarification of ${insight.ruleSection}
Incidents: ${insight.affectedCount}+ violations

CURRENT RULE:
"${insight.originalRuleText}"

PROPOSED AMENDMENT:
"${insight.proposedAmendment}"

RATIONALE:
${insight.rationale}

Generated by Inkloom Shield.`;
    navigator.clipboard.writeText(proposal);
    setCopied(true);
    setTimeout(() => setCopied(false), 2500);
  };

  const handleSubmit = () => {
    setSubmitted(true);
    setTimeout(() => { setSubmitted(false); onClose(); }, 2000);
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-slate-900/40 backdrop-blur-sm animate-fadeIn">
      <div className="relative w-full max-w-2xl bg-white border border-slate-200 rounded-xl shadow-xl overflow-hidden flex flex-col max-h-[90vh] animate-slideIn">
        {/* Header */}
        <div className="flex items-center justify-between px-5 py-4 border-b border-slate-100">
          <div className="flex items-center gap-3">
            <div className="w-8 h-8 rounded-lg bg-violet-600 flex items-center justify-center shrink-0">
              <Lightbulb className="w-4 h-4 text-white" />
            </div>
            <div>
              <div className="flex items-center gap-2">
                <span className="text-[10px] font-semibold px-2 py-0.5 rounded-full bg-violet-50 text-violet-700 border border-violet-200 uppercase tracking-wide">
                  Macro Insight
                </span>
                <span className="text-xs text-slate-400">{insight.affectedCount} repeat violations</span>
              </div>
              <h2 className="text-sm font-semibold text-slate-900 mt-0.5">{insight.title}</h2>
            </div>
          </div>
          <button
            onClick={onClose}
            className="p-1.5 text-slate-400 hover:text-slate-700 rounded-md hover:bg-slate-100 transition-colors"
          >
            <X className="w-4 h-4" />
          </button>
        </div>

        {/* Body */}
        <div className="p-5 overflow-y-auto space-y-4 text-sm">
          {/* Root cause */}
          <div className="p-4 bg-slate-50 border border-slate-200 rounded-lg">
            <div className="flex items-center gap-2 text-xs font-semibold text-slate-500 uppercase tracking-wide mb-2">
              <ArrowRight className="w-3.5 h-3.5" />
              Root-Cause Analysis
            </div>
            <p className="text-xs text-slate-600 leading-relaxed">{insight.description}</p>
          </div>

          {/* Side-by-side diff */}
          <div className="grid grid-cols-1 md:grid-cols-2 gap-3">
            <div className="border border-red-200 rounded-lg overflow-hidden">
              <div className="px-3 py-2 bg-red-50 border-b border-red-200 flex items-center justify-between">
                <span className="text-xs font-semibold text-red-700 flex items-center gap-1.5">
                  <ShieldAlert className="w-3.5 h-3.5" />
                  Current Rule
                </span>
                <span className="text-[10px] px-1.5 py-0.5 rounded bg-red-100 text-red-600 font-medium">Ambiguous</span>
              </div>
              <div className="p-3 bg-white">
                <p className="text-xs text-slate-600 leading-relaxed italic">
                  &ldquo;{insight.originalRuleText}&rdquo;
                </p>
              </div>
            </div>

            <div className="border border-emerald-200 rounded-lg overflow-hidden">
              <div className="px-3 py-2 bg-emerald-50 border-b border-emerald-200 flex items-center justify-between">
                <span className="text-xs font-semibold text-emerald-700 flex items-center gap-1.5">
                  <Check className="w-3.5 h-3.5" />
                  RFC Amendment
                </span>
                <span className="text-[10px] px-1.5 py-0.5 rounded bg-emerald-100 text-emerald-700 font-medium">Proposed</span>
              </div>
              <div className="p-3 bg-white">
                <p className="text-xs text-slate-700 leading-relaxed font-medium">
                  &ldquo;{insight.proposedAmendment}&rdquo;
                </p>
              </div>
            </div>
          </div>

          {/* Rationale */}
          <div className="p-4 bg-violet-50 border border-violet-100 rounded-lg">
            <h4 className="text-xs font-semibold text-violet-800 mb-1.5">Strategic Benefit</h4>
            <p className="text-xs text-slate-600 leading-relaxed">{insight.rationale}</p>
          </div>
        </div>

        {/* Footer actions */}
        <div className="flex items-center justify-between px-5 py-4 border-t border-slate-100 bg-slate-50">
          <span className="text-xs text-slate-400 hidden sm:inline">
            Ready for Brand Committee review
          </span>
          <div className="flex items-center gap-2 w-full sm:w-auto justify-end">
            <button
              onClick={handleCopy}
              className="flex items-center gap-1.5 px-3.5 py-2 text-xs font-medium text-slate-700 bg-white border border-slate-200 rounded-lg hover:bg-slate-50 transition-colors"
            >
              {copied ? <Check className="w-3.5 h-3.5 text-emerald-600" /> : <Copy className="w-3.5 h-3.5" />}
              {copied ? 'Copied!' : 'Copy RFC'}
            </button>
            <button
              onClick={handleSubmit}
              disabled={submitted}
              className="flex items-center gap-1.5 px-4 py-2 text-xs font-semibold text-white bg-violet-600 hover:bg-violet-700 rounded-lg transition-colors shadow-sm"
            >
              {submitted ? <><Check className="w-3.5 h-3.5" />Submitted!</> : <><Send className="w-3.5 h-3.5" />Submit to Brand Lead</>}
            </button>
          </div>
        </div>
      </div>
    </div>
  );
}
