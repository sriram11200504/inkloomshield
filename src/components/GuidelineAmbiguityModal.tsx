'use client';

import React, { useState } from 'react';
import { MacroInsight } from '@/lib/types';
import { Lightbulb, Copy, Check, FileText, Send, X, ArrowRight, ShieldAlert, Sparkles } from 'lucide-react';

interface GuidelineAmbiguityModalProps {
  insight: MacroInsight;
  isOpen: boolean;
  onClose: () => void;
}

export function GuidelineAmbiguityModal({ insight, isOpen, onClose }: GuidelineAmbiguityModalProps) {
  const [copied, setCopied] = useState(false);
  const [submitted, setSubmitted] = useState(false);

  if (!isOpen) return null;

  const handleCopy = () => {
    const fullProposal = `BRAND GOVERNANCE RFC // RULE AMENDMENT PROPOSAL
Subject: Clarification Proposal for ${insight.ruleSection}
Affected Areas: ${insight.affectedCount}+ incidents across recent marketing collaterals

CURRENT AMBIGUOUS RULE:
"""
${insight.originalRuleText}
"""

PROPOSED AMENDMENT:
"""
${insight.proposedAmendment}
"""

RATIONALE & IMPACT:
${insight.rationale}

Generated by Inkloom Shield Autonomous Governance Engine.`;

    navigator.clipboard.writeText(fullProposal);
    setCopied(true);
    setTimeout(() => setCopied(false), 2500);
  };

  const handleSubmit = () => {
    setSubmitted(true);
    setTimeout(() => {
      setSubmitted(false);
      onClose();
    }, 2000);
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-black/80 backdrop-blur-sm animate-fadeIn">
      <div className="relative w-full max-w-2xl bg-slate-900 border border-purple-500/30 rounded-2xl shadow-2xl overflow-hidden flex flex-col max-h-[90vh]">
        {/* Header */}
        <div className="flex items-center justify-between p-5 border-b border-slate-800 bg-purple-950/20">
          <div className="flex items-center gap-3">
            <div className="p-2 rounded-xl bg-purple-500/20 border border-purple-500/40 text-purple-300">
              <Lightbulb className="w-5 h-5" />
            </div>
            <div>
              <div className="flex items-center gap-2">
                <span className="text-xs font-mono font-semibold px-2 py-0.5 rounded bg-purple-500/20 text-purple-300 border border-purple-500/30">
                  MACRO GOVERNANCE INSIGHT
                </span>
                <span className="text-xs text-slate-400 font-mono">
                  {insight.affectedCount} Repeat Violations Detected
                </span>
              </div>
              <h2 className="text-lg font-bold text-white mt-0.5">{insight.title}</h2>
            </div>
          </div>
          <button
            onClick={onClose}
            className="p-1.5 text-slate-400 hover:text-white rounded-lg hover:bg-slate-800 transition-colors"
          >
            <X className="w-5 h-5" />
          </button>
        </div>

        {/* Content Body */}
        <div className="p-6 overflow-y-auto space-y-6 text-sm">
          {/* Executive Summary Alert */}
          <div className="bg-slate-950/80 border border-slate-800 rounded-xl p-4 space-y-2">
            <div className="flex items-center gap-2 text-purple-300 font-semibold text-xs uppercase tracking-wider">
              <Sparkles className="w-4 h-4 text-purple-400" />
              Root-Cause Flaw Diagnosis
            </div>
            <p className="text-slate-300 leading-relaxed text-xs">
              {insight.description}
            </p>
          </div>

          {/* Comparative Diff: Original Rule vs Proposed Revision */}
          <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
            {/* Vague Rule Box */}
            <div className="bg-rose-950/20 border border-rose-500/30 rounded-xl p-4 space-y-2">
              <div className="flex items-center justify-between text-xs">
                <span className="font-semibold text-rose-300 flex items-center gap-1.5">
                  <ShieldAlert className="w-4 h-4" />
                  Original Ambiguous Rule
                </span>
                <span className="text-[10px] font-mono bg-rose-500/20 text-rose-400 px-1.5 py-0.5 rounded">
                  Causes Friction
                </span>
              </div>
              <p className="text-xs text-rose-200/90 leading-relaxed italic bg-rose-950/40 p-2.5 rounded border border-rose-500/20">
                &ldquo;{insight.originalRuleText}&rdquo;
              </p>
              <p className="text-[11px] text-slate-400">
                Leaves room for subjective interpretation by copywriters, leading to repeated compliance rework.
              </p>
            </div>

            {/* Proposed Amendment Box */}
            <div className="bg-emerald-950/20 border border-emerald-500/30 rounded-xl p-4 space-y-2">
              <div className="flex items-center justify-between text-xs">
                <span className="font-semibold text-emerald-300 flex items-center gap-1.5">
                  <Check className="w-4 h-4" />
                  AI Clarified RFC Amendment
                </span>
                <span className="text-[10px] font-mono bg-emerald-500/20 text-emerald-400 px-1.5 py-0.5 rounded">
                  Recommended
                </span>
              </div>
              <p className="text-xs text-emerald-200/90 leading-relaxed font-medium bg-emerald-950/40 p-2.5 rounded border border-emerald-500/20">
                &ldquo;{insight.proposedAmendment}&rdquo;
              </p>
              <p className="text-[11px] text-slate-400">
                Provides concrete examples, approved phrasing templates, and explicit boundary rules.
              </p>
            </div>
          </div>

          {/* Rationale & Expected ROI */}
          <div className="bg-slate-950/60 border border-slate-800 rounded-xl p-4 space-y-2 text-xs">
            <h4 className="font-semibold text-slate-200 flex items-center gap-1.5">
              <ArrowRight className="w-3.5 h-3.5 text-purple-400" />
              Strategic Benefit for Brand Managers
            </h4>
            <p className="text-slate-300 leading-relaxed">
              {insight.rationale}
            </p>
          </div>
        </div>

        {/* Footer Actions */}
        <div className="flex items-center justify-between p-4 border-t border-slate-800 bg-slate-950/60">
          <span className="text-xs text-slate-400 font-mono hidden sm:inline">
            Status: Ready for Brand Committee Review
          </span>
          <div className="flex items-center gap-3 w-full sm:w-auto justify-end">
            <button
              onClick={handleCopy}
              className="flex items-center gap-1.5 px-3.5 py-2 text-xs font-medium text-slate-300 bg-slate-800 hover:bg-slate-700 hover:text-white rounded-lg transition-colors border border-slate-700"
            >
              {copied ? <Check className="w-4 h-4 text-emerald-400" /> : <Copy className="w-4 h-4" />}
              {copied ? 'Copied to Clipboard!' : 'Copy RFC Amendment'}
            </button>
            <button
              onClick={handleSubmit}
              disabled={submitted}
              className="flex items-center gap-1.5 px-4 py-2 text-xs font-semibold text-white bg-purple-600 hover:bg-purple-500 rounded-lg shadow-lg shadow-purple-600/30 transition-all"
            >
              {submitted ? (
                <>
                  <Check className="w-4 h-4" />
                  Submitted to Brand Board!
                </>
              ) : (
                <>
                  <Send className="w-4 h-4" />
                  Submit Proposal to Brand Lead
                </>
              )}
            </button>
          </div>
        </div>
      </div>
    </div>
  );
}
